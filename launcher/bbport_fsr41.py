def code(status):
    if status.get('supported'): return SUPPORTED
    reason, detail = status.get('reason'), status.get('detail', '')
    if reason == 'hardware':
        return GPU if 'AMD GPU required' in detail or 'unsupported by selected GPU' in detail else CAPABILITY
    return {'driver': DRIVER, 'provider': CAPABILITY, 'files': FILES, 'download': FILES,
            'interop': INTEROP, 'adapter': INTEROP, 'disabled': DISABLED,
            'checking': CHECKING}.get(reason, CHECK)


def route_index(upscaler, backend):
    return next((i for i, row in enumerate(ROUTES) if row[:2] == (upscaler, backend)), 0)


def preferred_route(statuses, preferred=None, version=None, backend=None):
    """One ranking for first launch and family selection; unknown results never qualify."""
    order = ([preferred] if preferred is not None else []) + list(range(len(ROUTES)))
    return next((i for i in order if statuses[i].get('supported') is True
                 and (version is None or ROUTES[i][0] == version)
                 and (backend is None or ROUTES[i][1] == backend)), None)


def method_statuses(port, data_dir, capabilities, fetch_fsr4vk, env=None):
    return [bbport_fsr412.method_status(method, capabilities) if version == 'fsr412'
            else bbport_fsr411.method_status(port, data_dir, method, capabilities, fetch_fsr4vk, env)
            for version, method, *_ in ROUTES]
