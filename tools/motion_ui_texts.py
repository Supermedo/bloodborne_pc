"""Generate overlay failure reasons from the launcher's shared catalog."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'launcher'))
import bbport_lang_motion as catalog

REASONS = ('Gpu', 'Vram', 'Features', 'Limits', 'Buffers')


def generate():
    languages = ['en', *(code for code in catalog.TEXTS if code != 'en')]
    rows = ',\n'.join('    {' + ', '.join(json.dumps(s, ensure_ascii=False)
                        for s in (catalog.TEXTS[code][key] for key in REASONS)) + '}' for code in languages)
    return '''// Generated by tools/motion_ui_texts.py; edit launcher/bbport_lang_motion.py.
// SPDX-License-Identifier: GPL-2.0-or-later
#pragma once
#include <cstdlib>
#include <cstring>

namespace MotionUi {
enum TextId { REASONS };
inline constexpr const char* languages[] = {LANGUAGES};
inline constexpr auto LanguageCount = sizeof(languages) / sizeof(languages[0]);
inline constexpr const char* texts[][TEXT_COUNT] = {
ROWS
};
static_assert(sizeof(texts) / sizeof(texts[0]) == LanguageCount);
inline const char* Text(TextId id) {
    const char* value = std::getenv("BB_UI_LANGUAGE");
    if (value) {
        for (unsigned i = 0; i < LanguageCount; ++i) {
            if (!std::strncmp(value, languages[i], 2) &&
                (!value[2] || value[2] == '-' || value[2] == '_'))
                return texts[i][id];
        }
    }
    return texts[0][id];
}
} // namespace MotionUi
'''.replace('REASONS', ', '.join(REASONS)).replace('TEXT_COUNT', str(len(REASONS))) \
   .replace('LANGUAGES', ', '.join(json.dumps(c) for c in languages)).replace('ROWS', rows)


def main():
    target = ROOT / 'gpu/shim/bbport_motion_ui.h'
    content = generate()
    if '--check' in sys.argv:
        if target.read_text(encoding='utf-8') != content:
            raise SystemExit('Object-motion translations need regeneration')
    else:
        target.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
