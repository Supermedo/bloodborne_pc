"""Generate overlay failure reasons from the launcher's shared catalog."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'launcher'))
import bbport_lang_vram as catalog


def generate():
    languages = list(catalog.TEXTS)
    rows = ',\n'.join('    {' + ', '.join(json.dumps(s, ensure_ascii=False)
                        for s in catalog.TEXTS[code][2:]) + '}' for code in languages)
    return '''// Generated by tools/motion_ui_texts.py; edit launcher/bbport_lang_vram.py.
// SPDX-License-Identifier: GPL-2.0-or-later
#pragma once
#include <cstdlib>
#include <cstring>

namespace MotionUi {
enum TextId { Gpu, Vram, Features, Limits, Buffers };
inline constexpr const char* languages[] = {LANGUAGES};
inline constexpr const char* texts[13][5] = {
ROWS
};
inline const char* Text(TextId id) {
    const char* value = std::getenv("BB_UI_LANGUAGE");
    if (value) {
        for (unsigned i = 0; i < 13; ++i) {
            if (!std::strncmp(value, languages[i], 2) &&
                (!value[2] || value[2] == '-' || value[2] == '_'))
                return texts[i][id];
        }
    }
    return texts[0][id];
}
} // namespace MotionUi
'''.replace('LANGUAGES', ', '.join(json.dumps(c) for c in languages)).replace('ROWS', rows)


if __name__ == '__main__':
    target = ROOT / 'gpu/shim/bbport_motion_ui.h'
    content = generate()
    if '--check' in sys.argv:
        if target.read_text(encoding='utf-8') != content:
            raise SystemExit('Object-motion translations need regeneration')
    else:
        target.write_text(content, encoding='utf-8')
