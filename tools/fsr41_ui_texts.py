"""Generate the overlay's FSR picker strings from the launcher's shared catalog."""
from pathlib import Path
import json
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'launcher'))
sys.path.insert(0,str(ROOT/'scripts'))
import bbport_fsr41 as texts
import fetch_fsr4vk
codes=list(texts.TEXTS)
assert codes[0]=='en' and len(codes)==13
rows=',\n'.join('    {'+', '.join(json.dumps(s,ensure_ascii=False) for s in texts.TEXTS[c])+'}' for c in codes)
header='''// Generated by tools/fsr41_ui_texts.py; edit launcher/bbport_fsr41.py.
// SPDX-License-Identifier: GPL-3.0-or-later
#pragma once
#include <cstring>
#include <cstdlib>
namespace Fsr41Ui {
enum TextId {Settings, Family, Recommended, Alternative, Compatibility,
             Supported, Gpu, Capability, Driver, Files, Check, Disabled, Interop, Checking,
             Help, Download, Recheck, Close, Selected, Unavailable, Method, Availability,
             Support, Details, Hint412Vk, Hint412Dx, Hint411Dx, Hint411Vk,
             MotionCacheLabel, MotionCacheHelp};
inline constexpr const char* languages[] = {LANGUAGES};
inline constexpr const char* texts[13][TEXT_COUNT] = {
ROWS
};
inline int Language() {
    const char* value=std::getenv("BB_UI_LANGUAGE");
    if (value) for(int i=1;i<13;++i)
        if(!std::strncmp(value,languages[i],2) && (!value[2] || value[2]=='-' || value[2]=='_')) return i;
    return 0;
}
inline const char* Text(int id) { return texts[Language()][id]; }
}
'''.replace('LANGUAGES',', '.join(json.dumps(c) for c in codes)).replace('ROWS',rows).replace('TEXT_COUNT', str(len(texts.KEYS)))
target=ROOT/'gpu/shim/bbport_fsr41_ui.h'
target.write_text(header,encoding='utf-8',newline='\n')
manifest = '''// Generated by tools/fsr41_ui_texts.py from scripts/fetch_fsr4vk.py.
// SPDX-License-Identifier: GPL-2.0-or-later
#pragma once
#include <cstdint>
namespace Fsr4VkPackage {
struct File { const char* name; uint64_t size; const char* sha256; };
inline constexpr File Files[] = {
''' + ',\n'.join('    {'+json.dumps(name)+', '+str(size)+', '+json.dumps(sha)+'}'
                for _, name, size, sha in fetch_fsr4vk.FILES) + '\n};\n}\n'
(ROOT/'gpu/shim/bbport_fsr4vk_manifest.h').write_text(manifest,encoding='utf-8',newline='\n')
print('PASS: generated shared FSR 4.1 overlay catalog for all 13 languages')
